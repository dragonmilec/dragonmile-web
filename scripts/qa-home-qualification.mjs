import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
const browser = await chromium.launch({executablePath:'C:/Program Files (x86)/Microsoft/Edge/Application/msedge.exe',headless:true})
const origin=process.env.QA_URL || 'http://127.0.0.1:5175'
const verified=[],errors=[]
try {
 for(const width of [1440,390,320]) {
  const page=await browser.newPage({viewport:{width,height:844},reducedMotion:'reduce'})
  page.on('pageerror',e=>errors.push(e.message))
  await page.goto(origin)
  await page.locator('.showcase-toggle').nth(1).click()
  const trigger=page.getByRole('button',{name:'查看資格',exact:true})
  const triggerBounds=await trigger.boundingBox(), panel=await page.locator('.showcase-panel.is-active').boundingBox()
  assert.ok(triggerBounds.y+triggerBounds.height<=panel.y+panel.height+1,'qualification trigger is not clipped at '+width)
  await trigger.click()
  const dialog=page.locator('#qualification-certificate-dialog')
  assert.ok(await dialog.evaluate(el=>el.open))
  assert.ok((await dialog.innerText()).includes('115-AU-5-50955037-1113'))
  assert.equal(await dialog.locator('time[datetime="2026-05-01"]').count(),1)
  assert.equal(await dialog.locator('time[datetime="2028-05-01"]').count(),1)
  assert.equal(await dialog.locator('img').getAttribute('src'),'/assets/credentials/certificate-2026.svg')
  await dialog.locator('img').evaluate(img=>img.decode())
  await page.screenshot({path:'qa-artifacts/qualification-home-fix-'+width+'.png'})
  await page.keyboard.press('Escape')
  assert.ok(await trigger.evaluate(el=>document.activeElement===el))
  assert.equal(await page.evaluate(()=>document.body.style.overflow),'')
  await trigger.click()
  await page.getByRole('link',{name:'完整資格資料',exact:true}).click()
  await page.waitForURL('**/about#qualification')
  const qualification=page.locator('#qualification')
  assert.ok((await qualification.innerText()).includes('115-AU-5-50955037-1113'))
  assert.ok(!(await qualification.innerText()).includes('112-AU-5-50955037-0876'))
  assert.equal(await qualification.locator('img').getAttribute('src'),'/assets/credentials/certificate-2026.svg')
  await page.waitForTimeout(300)
  await page.locator('.qualification-banner-trigger').click()
  assert.ok(await dialog.evaluate(el=>el.open))
  await page.keyboard.press('Escape')
  verified.push(width+'px: home button opens current certificate, close restores focus, qualification page and header share current metadata')
  await page.close()
 }
 const page=await browser.newPage({viewport:{width:390,height:844},reducedMotion:'no-preference'})
 await page.goto(origin)
 await page.locator('.hero-showcase').scrollIntoViewIfNeeded()
 await page.waitForFunction(()=>document.querySelector('.opening-hero')?.dataset.activeStep==='2')
 await page.getByRole('button',{name:'查看資格',exact:true}).click()
 assert.ok(await page.locator('#qualification-certificate-dialog').evaluate(el=>el.open))
 await page.waitForTimeout(2600)
 assert.equal(await page.locator('.opening-hero').getAttribute('data-active-step'),'2')
 await page.keyboard.press('Escape')
 verified.push('mobile scroll preserves opening; clicking qualification during playback pauses panel and opens certificate')
 assert.deepEqual(errors,[])
 console.log(JSON.stringify({verified,errors},null,2))
}finally{await browser.close()}
